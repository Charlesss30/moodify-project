import { chromium } from 'playwright-core'
import { pathToFileURL } from 'node:url'
import path from 'node:path'
import fs from 'node:fs'
import assert from 'node:assert/strict'
const browser=await chromium.launch({channel:'msedge',headless:true})
try {
  const page=await browser.newPage()
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  await page.goto(pathToFileURL(path.resolve('../tools/ai-label-review.html')).href)
  await page.locator('#annotator').fill('synthetic-browser-fixture')
  await page.locator('#file').setInputFiles('../docs/ai-evaluation/review-starter.json')
  await page.locator('#editor').waitFor({state:'visible'})
  assert.equal(await page.locator('#reviewed').isChecked(),false)
  await page.locator('#reviewed').click()
  assert.equal(await page.locator('#reviewed').isChecked(),false)
  await page.locator('#emotion').selectOption('Enjoyment')
  await page.locator('#reviewed').click()
  assert.equal(await page.locator('#reviewed').isChecked(),true)
  await page.locator('#next').click()
  assert.equal(await page.locator('#emotionLabel').isVisible(),false)
  await page.locator('#reviewed').click()
  assert.equal(await page.locator('#reviewed').isChecked(),false)
  await page.locator('#valence').fill('0.5')
  await page.locator('#arousal').fill('-0.5')
  await page.locator('#reviewed').click()
  assert.equal(await page.locator('#reviewed').isChecked(),true)
  const [download]=await Promise.all([page.waitForEvent('download'),page.locator('#export').click()])
  const rows=JSON.parse(fs.readFileSync(await download.path(),'utf8'))
  assert.equal(rows.length,48)
  assert.equal(rows.filter(r=>r.reviewed).length,2)
  assert.equal(rows[1].arousal,-.5)
  await page.locator('#arousal').fill('0')
  await page.locator('#arousal').blur()
  assert.equal(await page.locator('#reviewed').isChecked(),false)
  await page.reload()
  await page.locator('#restore').click()
  assert.equal(await page.locator('#arousal').inputValue(),'0')
  assert.equal(await page.locator('#reviewed').isChecked(),false)
  assert.deepEqual(errors,[])
  fs.mkdirSync('../.local-build/phase3-annotation',{recursive:true})
  await page.screenshot({path:'../.local-build/phase3-annotation/review.png',fullPage:true})
  fs.writeFileSync('../.local-build/phase3-annotation/result.json',JSON.stringify({status:'passed',scope:'Offline workflow with synthetic choices; not reviewed gold.'},null,2))
  console.log('PASS: offline label import, no automatic review, required labels, export, edit invalidation and local draft restore.')
} finally { await browser.close() }